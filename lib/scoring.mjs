// 像度 0~1。1 = 短的那条的词**全都在**长的那条里
function 像度(片段A, 片段B) {
  if (!片段A || !片段B || !片段A.size || !片段B.size) return 0
  const 小 = 片段A.size <= 片段B.size ? 片段A : 片段B
  const 大 = 小 === 片段A ? 片段B : 片段A
  // ⚠ 太短的（一两个词）不比 —— 「怕」「蓝色」这种单词撞上就算 1.0，
  //   那是假重复，不是真重复 ✓
  if (小.size < 3) return 0
  let 交 = 0
  for (const x of 小) if (大.has(x)) 交++
  return 交 / 小.size
}
