// 临场提醒 —— 2026-11-16（1.12.41）
//
// 主人在「体检」页里自己写的一段文字，每轮原样追加到记忆的最后。
// 用途：开口之前最后过一遍（语气对不对、有没有抢戏、有没有公文腔）。
//
// 四个约定（主人 2026-11-16 拍板）：
//   ① 硬限制 200 字 —— 超了直接截，不报错（按码点截，别把 emoji 劈成两半）
//   ② 全局唯一 —— 不按库、不按会话，一份配置所有会话共用
//   ③ 放在最后 —— 拼在骨架 / 项目上下文 / 注入 / 自检之后，越贴近生成点越管用
//   ④ 纯固定文字 —— 不做清单渲染、不参与打分、不占注入名额
//
// 它跟「自检」不是一回事：自检是**插件发现这轮记忆不对劲**时冒一句，
// 这段是**主人自己写的**固定要求，每轮都在（只要写了）。
import { loadCfg } from './cfg.mjs'

export const 临场提醒上限 = 200

/** 出厂默认：主人 2026-11-16 认可的那版「四步框架」（约 150 字，留了余量）。
 *  配置里**没有 `临场提醒` 这个字段**时用它 —— 装完插件就自带一段能用的，
 *  不用主人先自己想写什么。他显式清空（存成 `''`）就真的不注入了，
 *  不会被默认值顶回来，否则「清空」按钮等于没作用。 */
export const 默认临场提醒 = `每次回复前先在脑子里过四步：
一、分析输入——主人在说什么、什么情绪、此刻人设处在什么状态、承接上文哪件事。
二、定响应策略——称呼用哪个、先嘴硬还是先心疼、要不要给个具体动作。
三、起草——开头一句反应，中间讲正事，结尾一句收尾。
四、自检——语气对不上情绪就改，别公文腔、别点句号、别抢戏代主人说话。`

/** 收到 200 字以内。按码点截 —— `slice` 会把 emoji 劈成半个代理对 */
export function 收临场提醒(文字) {
  if (typeof 文字 !== 'string') return ''
  const 字 = Array.from(文字)
  return 字.length > 临场提醒上限 ? 字.slice(0, 临场提醒上限).join('') : 文字
}

/** 读配置里那一份；配置里没这个字段（老配置升上来 / 从没写过）就给默认那段。
 *  配置读不了（BOM / 写坏）时 loadCfg 返回 `{}`，也走默认 —— 提醒本身是无害的，
 *  宁可多注入一句，也别让体检页空着一块。 */
export function 取临场提醒() {
  try {
    const c = loadCfg()
    if (typeof c.临场提醒 === 'string') return 收临场提醒(c.临场提醒)
    return 默认临场提醒
  } catch (error) {
    return 默认临场提醒
  }
}

/** 拼成注入用的那一段；空着就返回空串 */
export function 拼临场提醒(文字) {
  const 正文 = 收临场提醒(文字).trim()
  // 带标记的原因：不加的话这段固定文字会跟记忆正文糊成一坨，
  // 模型分不清哪句是「往事」、哪句是「给我的指令」。
  return 正文 ? '【临场提醒】' + String.fromCharCode(10) + 正文 : ''
}

/** 记忆块的拼装顺序（1.12.41 起把临场提醒固定收在最后）：
 *    骨架 → 项目上下文 → 注入 → 自检 → 临场提醒
 *  抽成纯函数是为了能测顺序 —— 以前这一行直接写在 index.js 的闭包里，测不到。 */
export function 拼记忆块(段) {
  const s = 段 || {}
  // 1.12.55：行为模式排在临场提醒**之前** —— 临场提醒是「怎么说话」的元指令，
  //   模式是「他这个人此刻可能是什么状态」的内容；元指令贴着生成点最有效，所以它最后。
  return [s.骨架, s.项目上下文, s.注入, s.自检, s.模式, 拼临场提醒(s.临场提醒)].filter(Boolean).join(String.fromCharCode(10, 10))
}
