test('⑥ 解析洗键：整格就是键，形状判据与提炼那边**一模一样**', () => {
  const r = 解析洗键('1|她.身高\n2|约定.身边位置\n3|拼团.状态', 4)
  assert.equal(r[0], '她.身高')
  assert.equal(r[1], '约定.身边位置')
  assert.equal(r[2], '拼团.状态')
  // ⚠⚠ 带数字的不算键 —— 提炼那边一直有这条，这边漏过（于是 `她.身高170` 能被收进来）
  assert.equal(解析洗键('1|她.身高170', 2)[0], null, '带数字的不算键（两个解析器的判据必须一致）')
  assert.equal(解析提炼('1|正文|词一 词二|2026-01-01|1|她.身高170', 2)[0].键, null, '提炼那边同样要挡住')
  // 没有点的、三段的、太长的都不算
  assert.equal(解析洗键('1|她身高', 2)[0], null, '没有点的不算键')
  assert.equal(解析洗键('1|她.话.内容', 2)[0], null, '三段的不算键')
  assert.equal(解析洗键('1|' + '她'.repeat(20) + '.' + '高'.repeat(20), 2)[0], null, '太长的不算键')
  // 归一键 的清洗要先跑：全角点、冒号、竖线、反引号都归成点
  assert.equal(归一键('她．身高'), '她.身高')
  assert.equal(归一键('她：身高'), '她.身高')
  assert.equal(归一键('`她.身高`'), '她.身高', '模型加的引号该被剥掉')
  assert.equal(归一键(' 她.身高 '), '她.身高')
  assert.equal(归一键('她 身高'), '她身高', '空格该被去掉')
  assert.equal(归一键(null), '')
  // ⚠ 大小写归一（键要稳、要通用）
  assert.equal(归一键('DSH.版本'), 'dsh.版本', '键该归一成小写，否则同一个键两种写法碰不上')
})

