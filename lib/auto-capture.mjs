// ⭐ 2026-11-18（1.12.53）：句子级闸门。
//
// 起因：用户说了四句话，四条全被当记忆收了 ——
//   「真的吗？妈妈妈妈，我喜欢黑丝还是光腿？」  ← 在问，不是陈述
//   「如果光腿是大白饭，黑丝是卤肉饭，那白丝应该是我更喜欢吃的什么饭？」 ← 比喻
// 因为 归类() 拿**整段**去撞六类正则，一个「喜欢」就把整句收了。
// 后果：下一轮字面重合又被召回，闲聊把真答案挤到最后一名（实测 P 0.35 vs 0.288）。
//
// ⚠ 两个关键教训（Gemini 评审挑出来的，别改回去）：
//   1. 假设词（如果/假如/万一/就像）修饰的是**整句**，不是逗号前那小半句 ——
//      「如果明天不下雨，我就去爬山」只按子句切的话，后半句「我就去爬山」会被
//      当成既定事实收进来。所以假设检查必须在切子句**之前**、按整句做。
//   2. 疑问判据不能裸匹配「还是/什么/哪/怎么」——
//      「我还是更喜欢喝冰美式」「我什么辣都吃」「不管去哪家我都点微辣」
//      全是正常陈述，裸匹配会误杀一大片。只认「句末疑问语气」和「强疑问结构」。
export const 假设词 = /(?:如果|假如|要是|假设|万一|就像|好比|比如|例如|若是|倘若)/
export const 强疑问词 = /(?:难道|为什么|为啥|怎么会|是不是|有没有|能不能|可不可以|什么|怎么|咋|哪)/

/** 整句是不是「虚拟语气」（假设/比喻）—— 命中就整句不要，一个字都不收。 */
export function 是假设句(text) {
  return 假设词.test(String(text || ''))
}

/** 整句是不是强反问（以问号结尾且带强疑问词）—— 这种整句收不住，宁可全丢。 */
export function 是强反问(text) {
  const 文 = String(text || '').trim()
  return /[？?]\s*$/.test(文) && 强疑问词.test(文)
}

/** 按逗号/顿号/分号切成子句（用于逐句判类）。 */
export function 切子句(text) {
  return String(text || '')
    .split(/[，,、；;]/)
    .map((s) => s.trim())
    .filter(Boolean)
}

/** 子句是不是疑问语气：只看句末（问号 / 吗呢吧），不看句中。 */
export function 是疑问子句(s) {
  const 文 = String(s || '').trim()
  if (!文) return false
  if (/[？?]\s*$/.test(文)) return true
  return /(?:吗|呢|吧|多久|几次|多少)\s*[？?]?\s*$/.test(文)
}

/** 这句话属于哪一类（不命中返回 null）。 */
export function 归类(text) {
  const 文 = String(text || '')
  if (文.trim().length < 4) return null
  for (const r of 类别规则) if (r.正则.test(文)) return r.类
  return null
}

/** 把一条消息拆成可判定的片段：按句末标点/换行切，太短的并到上一段。
 *  为什么：长消息会被 该自动收 的 400 字上限整条丢掉（真会话实测漏掉偏好/日期）。 */
export function 拆片段(text) {
  const 文 = String(text || '')
  const 粗 = 文.split(/(?<=[。！？!?~…\n])/).map((s) => s.trim()).filter(Boolean)
  const 出 = []
  for (const s of 粗) {
    if (s.length < 6 && 出.length) {
      出[出.length - 1] += s
      continue
    }
    出.push(s)
  }
  return 出.length ? 出 : [文.trim()]
}

/** 这条自动抽取的条目要不要收。
 *  返回 { 类, 档: 'strong' | 'detail' }；不收返回 null。
 *  strong：命中六类之一，直接落库；
 *  detail：只含具体名词/时间，按低重要度落库、每天封顶（由调用方控制）。 */
export function 该自动收(text) {
  const 文 = String(text || '').trim()
  if (文.length < 4 || 文.length > 400) return null

  // ⚠ 顺序很重要：**性质档必须排在虚拟语气拦截之前**。
  //   梦/虚构/假设（「假设你是只猫」「梦见舞台变成温室」）本来就该收，只是渲染时标「（梦）」，
  //   不能被「假设句一律丢」误杀 —— 这正是 1.12.3 加的档位存在的理由。
  const 性 = 判性质(文)
  if (性) return { 类: '性质', 档: 'nature', 性质: 性.性质, 名: 性.名 }

  // ⭐ 1.12.53：整句级的两个闸门，必须在切子句之前做（见上面 假设词 那段注释）。
  //   假设句整句丢：比喻/条件句里的「喜欢」不是真偏好。
  if (是假设句(文)) return null
  //   强反问整句丢：「难道我喜欢吃香菜很奇怪吗？」这种整句否定，切开了容易记反。
  if (是强反问(文)) return null

  // ⭐ 1.12.53：改成**子句级**判类 —— 长句里只要有一个真正在陈述的偏好子句就收，
  //   但疑问子句（「还是什么饭？」）和碎句（<4 字）跳过。
  //   阈值 4 不是 6：中文最干净的偏好记忆恰恰是 4~5 字（「我爱吃辣」「我不吃香菜」）。
  for (const 句 of 切子句(文)) {
    if (句.length < 4) continue
    if (是疑问子句(句)) continue
    const 类 = 归类(句)
    if (类) return { 类, 档: 'strong' }
  }

  if (文.length >= 8 && (细节词.test(文) || 时间词.test(文))) return { 类: 'detail', 档: 'detail' }
  return null
}

/** 跟库里已有的像不像（同一件事就别重复落）。返回命中的旧条目或 null。 */
export function 撞旧条(memories, text) {
  const 目标 = 词集(text)
  for (const m of memories || []) {
    if (!m || m.已被取代 || m.别记) continue
    if (typeof m.text !== 'string') continue
    const 像 = 像度(目标, 词集(m.text))
    if (像 >= 真重复门槛) return { 条: m, 像 }
  }
  return null
}
