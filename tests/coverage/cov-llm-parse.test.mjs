test('⑦ `n/a` 不再被收成键 `n.a`（2026-11-15 已修）', () => {
  // 曾经是个真缺口（本条测试第一版记录的就是那个行为）：
  //   解析洗键 先调 归一键，而归一键 会把末尾的 `/` 归一成 `.`
  //   （`s.replace(/[/／>＞-]{1}(?=[^.]*$)/, '.')`，且随后 toLowerCase），
  //   于是 `n/a` 走到黑名单那一行时**已经是 `n.a`**，正则里的 `n\/a` 永远匹配不上；
  //   偏偏 `n.a` 又符合键的形状 `^[^.]{1,12}\.[^.]{1,12}$` ⇒ 被当成正经键收进库。
  //   后果：模型用 `n/a` 表示「这条没有键」时，所有这类条目共享同一个键 n.a，
  //   按键收敛时被当成「同一件事」互相埋掉 —— 正是万能键要防的那种乱埋。
  // 修法（2026-11-15）：黑名单改成**原文与归一后各判一次** ——
  //   原文挡 `n/a` / `N/A`，归一后挡 `n.a` 与带引号的变体（归一会去掉引号，原文反而匹配不上）。
  assert.equal(归一键('n/a'), 'n.a', '归一键 仍把 / 变成 . —— 这是它该做的，修的是洗键那边的判定')
  for (const 填充 of ['n/a', 'N/A', 'n.a', '「n/a」', 'na', 'none', '跳过', '留空', '无', '不详']) {
    assert.equal(解析洗键('1|' + 填充, 2)[0], null, '`' + 填充 + '` 该当留空，不该被收成键')
  }
  // 对照：正经键照收，带数字的仍挡（那两条判据没被这次改动碰坏）
  assert.equal(解析洗键('1|她.身高', 2)[0], '她.身高', '正经键不受影响')
  assert.equal(解析洗键('1|她.身高170', 2)[0], null, '带数字的仍不算键')
})

