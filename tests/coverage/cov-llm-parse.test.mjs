//
// ⚠ 只测纯解析层（取日期 / 解析提炼 / 解析扩词 / 解析洗键）与提示词常量。
//   问模型 / 自动扩词 / 取模型 需要真宿主 ctx.llm + 真库，投入产出比低，不在这里测。
//
// 要守住的不变量：
//   ① 解析层要**极度容错**：模型可能只回两格/三格、某格留空、正文里本来就有竖线、
//      把重要度写成「2」或「很重要」—— 任何一格写歪都**只影响它自己**，不许污染正文；
//   ② 切格顺序要紧：**先摘事实键（在最尾巴）、再认检索词格**，找到检索词格后
//      左边全是正文、右边才是日期/重要度。（第一版从右往左一格一格切，模型给个怪重要度时
//      第二刀把它当日期切掉了 ⇒ 检索词也切不掉 ⇒ 整串竖线全粘在正文尾巴上）；
//   ③ 「跳过」要用**第一格**判，不能用切完的结果判 —— 模型写「跳过||||」，
//      切完剩 `跳过|||`，`/^跳过$/` 认不出来 ⇒ 本该扔掉的话被当成真记忆存进库（实测踩过）；
//   ④ `取日期` 要能容忍「不知道/无/空/-」，且**只认机器日期**：
//      「去年冬天」这种模型自己都没法定位的，宁可空着让人在界面上补，也不许猜；
//   ⑤ 键的判据要**很紧**（正好一个点、两边都是短的中文/字母、无空格、不带数字），
//      且**带数字的不算键**（`她.身高170` ✗ —— 写了值就成了摘要，身高一变键也变，永远碰不上）；
//   ⑥ 两个解析器的键判据必须**一模一样**（提炼那边「在整行尾巴上认一格」，
//      洗键那边「整格就是键」，场景不同但规则必须一致，不然两边会打架）；
//   ⑦ **万能键一律当留空**（`…话.内容` 能把「我饿了」「今天下雨」「我喜欢你」全装进去 ⇒ 乱埋）；
//   ⑧ 提示词里那几条「禁令」不许被悄悄改掉（人称不能写死「她」、白话大词黑名单要在）。
//
