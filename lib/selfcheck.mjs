// lib/selfcheck.mjs —— 自检摘要：这一轮的记忆「有没有毛病」，一句话说给它自己听
// ============================================================================
// 2026-11-10（1.10.5，能力清单里的「自检摘要」）。起因：
//   体检页签、/health、trace 全都是**画给主人看的**。它自己在对话里看不见自己的状态：
//   「这轮一条都没想起来」「这轮塞满了上限」「记忆块快吃满预算了」—— 全要等主人哪天去翻设置页 ✗
//   体检的意义应该是「她自己知道这轮不对劲，下轮就知道该怎么问 / 该少记点」。
//
// 三条硬约束（省白饭 + 不打扰）：
//   ① **正常时一个字都不输出** —— 空注入在闲聊里是常态，天天喊狼来了等于没信息；
//   ② **判据全在注入路径的内存里现成就有**（selected / scored / gate / 字数），
//      **不读 traces、不扫库、不发请求** → 每轮 0 次 IO；
//   ③ 拼进现有那条 `systemPrompt.context`（本来就每轮追加），**不新增宿主触点**，
//      它已经在缓存尾部、不破坏系统提示词缓存。
//
// 跟宿主的解耦：这个文件不 import 任何宿主接口，纯函数 → 不启动 DSH 就能单测。
// 连分词都不依赖（不 import scoring / lexicon）：判「是不是在问」用一条正则就够，
//   而且**故意**不去读 scoring 里那份疑问词表 —— 那份是给「宽退」用的内部细节，
//   哪天它改了（1.10.1 就改过一次），自检不该跟着抖。

/** 自检整句最多多少字：再多就成了第二条注入，得不偿失 */
export const 自检上限 = 60

// 「这句像不像在提问」：问号，或口语里常见的疑问词。
//   宁可漏判（当成陈述句 → 不提示）：误判成「在问」会在每段闲聊后面挂一条废话。
const 问句样 = /[?？]|什么|为啥|为什么|怎么|怎样|如何|哪个|哪些|哪儿|哪里|谁|多少|几点|几号|是不是|有没有|能不能|可不可以|吗$|呢$|嘛$/

export function 是问句(query) {
  const 句 = String(query || '').trim()
  if (!句) return false
  return 问句样.test(句)
}

/**
 * @param {{query?:string, 选中?:number, 候选?:number, gate?:any, 字?:number, 骨架字?:number, maxItems?:number, 预算?:number}} o
 *   query  这一轮的查询；选中 真正进提示词的条数；候选 过了门槛的条数（含被上限挤掉的）；
 *   gate   问句门的结果（被挡时有值）；字 注入文本字数；骨架字 骨架层字数；
 *   maxItems / 预算 来自 policy
 * @returns {string} 没毛病返回 ''；有毛病返回一句括号小字
 */
export function 自检(o) {
  const 源 = o && typeof o === 'object' ? o : {}
  const 选中 = Math.max(0, 源.选中 | 0)
  const 候选 = Math.max(选中, 源.候选 | 0)
  const 字 = Math.max(0, 源.字 | 0)
  const 骨架字 = Math.max(0, 源.骨架字 | 0)
  const 上限条 = 源.maxItems > 0 ? 源.maxItems | 0 : 6
  const 预算 = 源.预算 > 0 ? 源.预算 | 0 : 800
  const 问 = 是问句(源.query)

  const 句 = []
  // ① 人家在问，但一条都没想起来 —— 这是最容易「答得理直气壮但其实是编的」的场合
  if (!选中 && 问) {
    句.push(源.gate ? '这句在问，但太短/太泛，没去翻库' : '这句在问，库里没有落得上的')
  }
  // ② 塞满上限：说明还有更淡的没进来，回答时别当成「我就只记得这些」
  if (选中 > 0 && 选中 >= 上限条 && 候选 > 选中) {
    句.push('塞满了 ' + 上限条 + ' 条上限，另有 ' + (候选 - 选中) + ' 条没进来')
  }
  // ③ 字数吃紧：骨架 + 注入快把预算吃满，下轮值得挑更少的
  if (字 + 骨架字 >= 预算 * 0.85) {
    句.push('记忆块快吃满 ' + 预算 + ' 字预算')
  }
  if (!句.length) return ''
  const 话 = '（记忆自检：' + 句.join('；') + '）'
  // '…）' 占 2 个字，所以截到 上限-2，拼完正好 ≤ 上限
  return 话.length > 自检上限 ? 话.slice(0, 自检上限 - 2) + '…）' : 话
}
