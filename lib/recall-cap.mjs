// lib/recall-cap.mjs —— 召回「这趟上限」的纯函数（2026-10-30，审查 P2-3）
//
// 背景（GPT 整改清单 P2-3 的疑点）：
//   「按 P 排序后用第一条 C 决定召回上限」—— 排序用 P（总分），上限却用
//   第一条（P 最高）的 C（证据分）。P = C × 鲜活度乘数，P 最高 ≠ C 最高：
//   一条不新鲜但撞得准的条目 C 高、P 低，会被排到后面；一条新鲜的但证据弱的
//   条目 P 高、C 低，会排第一 —— 拿它的低 C 去定上限，就把「证据其实很强的」
//   那一批名额压没了。
//
// 业务定义（recall 里注释写的）：上限看的是「这一趟有没有一句真正贴的」——
//   「贴不贴」是 C（证据），不是 P（总分/鲜活度）。所以上限应取**所有够格条目里
//   最高的 C**，而不是排序后第一条的 C。C 已过 threshold 才进候选，够格的都在。
//
// 分档是原来 recall 里的常量（[0.6, maxItems] / [0.5, 4] / [0.4, 3] / [0, 1]），
// 搬进函数里用调用方的 maxItems 拼第一档，方便测试锁定行为：
//   最高 C >= 0.6 → maxItems 条；>= 0.5 → 4；>= 0.4 → 3；再低 → 1 条。

// 事件们：去重后的候选行数组（每行 { m, s: { P, C } }），已按 P 排序。
// maxItems：政策里的最大条数。返回这一趟该给的条数（调用方再对 maxItems 截断）。
export function 事件本趟上限(事件们, maxItems) {
  if (!Array.isArray(事件们) || !事件们.length) return 0
  let 最高C = 0
  for (const row of 事件们) {
    const c = row && row.s && typeof row.s.C === 'number' ? row.s.C : 0
    if (c > 最高C) 最高C = c
  }
  const 分档 = [
    [0.6, maxItems],
    [0.5, 4],
    [0.4, 3],
    [0, 1],
  ]
  for (const [线, 条] of 分档) {
    if (最高C >= 线) return 条
  }
  return 1
}
