    // ⚠⚠ 第二条：宁可不给
    //   为什么敢让她「大量留空」：留空的老条目**保持原样**（不会被卷进合并），
    //   而给错的键会把一条正经记忆**悄悄**标成「已被取代」—— 那是不可逆的信息损失 ✗
    //   所以这一步的**默认答案是「留空」**，只有真拿得准才填。
