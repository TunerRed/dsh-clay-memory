test('④ 取日期：模型爱写的「没有」一律当 null，不许猜', () => {
  for (const s of ['不知道', '不详', '未知', '无', '没有', '空', '不明确', '-', '--', '—', '——', '?', '？？']) {
    assert.equal(取日期(s), null, `「${s}」该当成没有日期`)
  }
  assert.equal(取日期(''), null)
  assert.equal(取日期(null), null)
  assert.equal(取日期(undefined), null)
  assert.equal(取日期('   '), null, '纯空白该当没有')
})

test('④ 取日期：只认机器日期，「去年冬天」这种宁缺毋滥', () => {
  // 认得的写法：年-月-日，分隔符可以是 - / . 或中文年月
  const d = 取日期('2026-09-17')
  assert.ok(d && d.at, '标准机器日期该认出来')
  assert.equal(d.猜年, false, '给了年份就不算猜')
  assert.equal(new Date(d.at).toISOString().slice(0, 10), '2026-09-17')
  assert.ok(取日期('2026/09/17'), '斜杠分隔也该认')
  assert.ok(取日期('2026.09.17'), '点分隔也该认')
  assert.ok(取日期('2026年9月17日'), '中文年月日也该认')
  // ⚠ 模型自己都没法定位的相对说法 → 一律 null（界面上有「补日期」按钮，让人来补）
  assert.equal(取日期('去年冬天'), null, '「去年冬天」不许猜 —— 猜错比空着更坏')
  assert.equal(取日期('前几天'), null)
  assert.equal(取日期('某个下午'), null)
  assert.equal(取日期('小时候'), null)
})

test('④ 取日期：范围与合法性校验（越界、2月30日一律丢）', () => {
  // 年份范围 1900 < y < 2200
  assert.equal(取日期('1899-01-01'), null, '1900 以前该丢')
  assert.equal(取日期('2201-01-01'), null, '2200 以后该丢')
  assert.ok(取日期('1901-01-01'), '范围内的年份该认')
  // 月日越界
  assert.equal(取日期('2026-13-01'), null, '13 月不存在')
  assert.equal(取日期('2026-00-10'), null, '0 月不存在')
  assert.equal(取日期('2026-01-32'), null, '32 号不存在')
  assert.equal(取日期('2026-01-00'), null, '0 号不存在')
  // ⚠ 不存在的日子（光看范围是过了的）要靠 日期合法 挡住
  assert.equal(取日期('2026-02-30'), null, '2月30日这种不存在的日子必须丢掉')
  assert.equal(取日期('2026-02-29'), null, '2026 是平年，2/29 不存在')
  assert.ok(取日期('2024-02-29'), '2024 是闰年，2/29 该认')
  assert.equal(取日期('2026-04-31'), null, '4 月没有 31 号')
})

test('④ 取日期：只给月日 → 年份按「最近的过去」算，并标出是猜的', () => {
  const 现在 = new Date()
  const 今年 = 现在.getUTCFullYear()
  // 找一个「今年已经过去了」的月日（用去年同月日一定安全）与一个「今年还没到」的
  const r = 取日期('09-17')
  assert.ok(r && r.at, '月-日该认出来')
  assert.equal(r.猜年, true, '没给年份必须标「猜年」—— 让人在界面上看得出这是推算的')
  const 推出 = new Date(r.at).toISOString().slice(0, 10)
  assert.match(推出, /^\d{4}-09-17$/, '月日部分要照抄：' + 推出)
  // 规则是「还没到 → 那就是去年的」：推出来的那天不能晚于今天
  assert.ok(new Date(r.at).getTime() <= Date.now(), '推出来的日期该是「最近的过去」，不能是未来：' + 推出)
  assert.ok(Number(推出.slice(0, 4)) >= 今年 - 1, '年份不该推到很久以前：' + 推出)
  // 月日越界也要挡住
  assert.equal(取日期('13-45'), null)
  assert.equal(取日期('02-30'), null, '2月30日不存在')
})

