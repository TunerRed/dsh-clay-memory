// 自动入库（1.12.1 起）—— 把「钩子」从候选区升级成规则直接落库
//
// 为什么改：真会话 360 轮实测，模型只主动调了 11 次 remember，钩子捡到的 8 条全躺在候选区
// 没人点「记下」。写入覆盖率因此只有 ~37%（27 个考点只覆盖 10 个）。
// dsh-soul 的做法说明差距不在算法在**责任归属**：写入该是代码的事，不该等模型心情。
//
// 只自动收六类（其余仍进候选区等人过目）：
//   constraint 硬性要求 / decision 决定改动 / preference 喜好 / date 日期时间 / place 地点 / item 物品
// 自动收的条目：
//   · importance 低（默认 0.4），不抢高价值记忆的位置
//   · source = '自动抽取'，界面上看得清是谁写的
//   · 原话一并存上（原话 ≤ 300 字），召回零命中时能回捞
//   · 走 像度 去重，同一年内几乎一样的话不会重复落库

import { 词集, 像度, 真重复门槛 } from './scoring.mjs'

export const 自动类别 = ['constraint', 'decision', 'preference', 'date', 'place', 'item']
export const 自动重要度 = 0.4
export const 细节重要度 = 0.3
export const 性质重要度 = 0.3
export const 细节每天上限 = 60

// 性质档（1.12.3）：梦 / 虚构 / 假设不是「事实」，但也不能丢 ——
//   丢了就等于系统从来没听见过（benchmark 的「梦里舞台变温室」就是这么丢的）。
//   收进来必须带 nature 标签，渲染时由 `性质标签()` 加「（梦）」，不许当事实念。
// ⚠ 假设只认「假设/假如/要是」这类显式说法，不认普通的「如果…就…」——
//   否则每句带条件的话都会被收成记忆，库里会堆满「如果有空就去看展」。
export const 性质线索 = [
  { 性质: 'dream', 名: '梦', 正则: /(?:梦见|梦到|做梦|梦里|梦见了)/ },
  { 性质: 'fiction', 名: '虚构', 正则: /(?:编一个|编个|编了|虚构|故事里|小说里|扮演|假装)/ },
  { 性质: 'hypothesis', 名: '假设', 正则: /(?:假设|假如|要是[^\n。！？]{0,20}(?:就|的话)|真要是)/ },
]

/** 这句是不是「梦 / 虚构 / 假设」。返回 { 性质, 名 } 或 null。 */
export function 判性质(text) {
  const 文 = String(text || '').trim()
  if (文.length < 6 || 文.length > 300) return null
  for (const r of 性质线索) if (r.正则.test(文)) return { 性质: r.性质, 名: r.名 }
  return null
}

// 低置信档「细节」：命中一处具体名词或时间就算。
// 为什么需要：PUB01 的真实口吻是碎片叙事（「今天剧场冷得像冰箱」「拿暖宝宝贴了后背」），
// 六类规则只覆盖 8%，而题问的恰恰是这些碎片里的东西。全部按低重要度收、每天封顶，
// 换取覆盖率，不至于把注入挤满。
export const 细节词 = /(?:楼|层|柜|抽屉|门口|楼下|楼上|店里|钱包|包里|口袋|箱子|阳台|窗|厨房|桌|床|书架|灯|扳手|笔|伞|水壶|杯子|钥匙|药|电池|耳机|眼镜|手机|外套|雨衣|暖宝宝|地铁|公交|站|面包店|超市|剧场|排练|演出|海报|票据|发票|明信片|录音|歌|电影|书|猫|狗|薄荷|花|茶|咖啡|饭|面|汤|饼)/
const 时间词 = /(?:下周|上周|这周|周末|周[一二三四五六日天]|\d{1,2}\s*点|\d{1,2}\s*月|[一二三四五六七八九十]{1,3}月|月底|年初|生日|昨天|明天|今天)/

// 线索正则：宁可漏，不要贪 —— 误收一句闲聊会一直挂在注入里。
// 2026-11-11 调宽过一轮：原来只认「放在…上」这类完整句式，PUB01 的真实口吻
// （「我住四楼，楼梯窄，搬灯架费劲」）一条都抓不到，覆盖率只有 14.4%。
export const 类别规则 = [
  // 硬性要求：以后别 / 不要 / 必须 / 记得 —— 边界和要求最该留住
  { 类: 'constraint', 正则: /(?:不要|不能|不许|禁止|必须|只能|只准|务必|记得|记住|以后别|别再)/ },
  // 决定 / 改动：因为所以、改成、以后就、定下来
  { 类: 'decision', 正则: /(?:因为|所以|决定|改成|改用|换成|以后就|定下来|就这么定)/ },
  // 喜好：喜欢 / 讨厌 / 怕 / 偏爱 / 更愿意
  { 类: 'preference', 正则: /(?:喜欢|讨厌|爱吃|受不了|最怕|偏爱|更喜欢|更愿意|不太喜欢|不擅长|拿手)/ },
  // 日期时间：具体日子 / 周几 / 下周 / 月底 / 几点
  { 类: 'date', 正则: /(?:\d{1,2}\s*月\s*\d{1,2}\s*[日号]|[一二三四五六七八九十]{1,3}月[一二三四五六七八九十]{1,3}[日号]|下周|这周|上周|周末|周[一二三四五六日天]|月底|年初|年后|生日是)/ },
  // 地点：住在 / 放在 / 搁在 / 搬到 / 塞进 / 收在 + 处所词
  { 类: 'place', 正则: /(?:住|搬到|放在|搁在|塞进|收在|挂在)(?:在|到|进)?[^\n。！？]{0,14}(?:楼|层|屋|房|间|门|柜|架|台|桌|床|抽屉|箱子|包|里|内|旁|边|面|附近|楼下|楼上|门口|角落)/ },
  // 物品：带数量词的拿 / 借 / 买 / 带 / 收 + 具体东西
  { 类: 'item', 正则: /(?:一把|一个|一只|一盒|一支|一瓶|一袋|一双|一副|一本|一张|一块)[^\n。！？]{0,12}(?:扳手|灯|笔|伞|水壶|杯子|书|钥匙|卡|药|刀|剪|钳|锤|电池|耳机|眼镜|手机|钱包|外套|雨衣|暖宝宝)/ },
]

/** 这句话属于哪一类（不命中返回 null）。 */
export function 归类(text) {
  const 文 = String(text || '')
  if (文.trim().length < 4) return null
  for (const r of 类别规则) if (r.正则.test(文)) return r.类
  return null
}

/** 把一条消息拆成可判定的片段：按句末标点/换行切，太短的并到上一段。
 *  为什么：长消息会被 该自动收 的 400 字上限整条丢掉（真会话实测漏掉偏好/日期）。 */
export function 拆片段(text) {
  const 文 = String(text || '')
  const 粗 = 文.split(/(?<=[。！？!?~…\n])/).map((s) => s.trim()).filter(Boolean)
  const 出 = []
  for (const s of 粗) {
    if (s.length < 6 && 出.length) {
      出[出.length - 1] += s
      continue
    }
    出.push(s)
  }
  return 出.length ? 出 : [文.trim()]
}

/** 这条自动抽取的条目要不要收。
 *  返回 { 类, 档: 'strong' | 'detail' }；不收返回 null。
 *  strong：命中六类之一，直接落库；
 *  detail：只含具体名词/时间，按低重要度落库、每天封顶（由调用方控制）。 */
export function 该自动收(text) {
  const 文 = String(text || '').trim()
  if (文.length < 4 || 文.length > 400) return null
  const 类 = 归类(文)
  if (类) return { 类, 档: 'strong' }
  // 性质档优先于「细节」：梦/虚构/假设这类句子往往也含具体名词，
  //   先按性质收，才能带上 nature 标签、渲染时加「（梦）」——否则会被当成事实。
  const 性 = 判性质(文)
  if (性) return { 类: '性质', 档: 'nature', 性质: 性.性质, 名: 性.名 }
  if (文.length >= 8 && (细节词.test(文) || 时间词.test(文))) return { 类: 'detail', 档: 'detail' }
  return null
}

/** 跟库里已有的像不像（同一件事就别重复落）。返回命中的旧条目或 null。 */
export function 撞旧条(memories, text) {
  const 目标 = 词集(text)
  for (const m of memories || []) {
    if (!m || m.已被取代 || m.别记) continue
    if (typeof m.text !== 'string') continue
    const 像 = 像度(目标, 词集(m.text))
    if (像 >= 真重复门槛) return { 条: m, 像 }
  }
  return null
}
